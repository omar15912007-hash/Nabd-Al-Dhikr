def build_qa_pairs(
    cat_id: str,
    cat_name: str,
    dhikr_text: str,
    short_virtue: str,
    source_ref: str,
    repeat_num: int,
    vocab: list[dict[str, str]],
) -> list[dict[str, Any]]:
    profile = CATEGORY_PROFILES[cat_id]
    snippet = extract_dhikr_snippet(dhikr_text, max_words=4)
    snippet_plain = normalize_arabic(snippet)
    first_word = vocab[0]["word"]
    first_word_plain = normalize_arabic(first_word)
    repeat_str = format_repeat_label_ar(repeat_num)

    # 17-18 unique, authentic, multi-dialect & emotional user questions
    candidates = [
        f"ما فضل ذكر {snippet_plain}؟",
        f"متى أقول {snippet_plain}؟",
        f"كم مرة أكرر ذكر {snippet_plain}؟",
        f"ما معنى كلمة {first_word_plain} في هذا الذكر؟",
        f"عايز أفهم معنى {snippet_plain} ببساطة",
        f"وش فضل وتوقيت {snippet_plain} في {cat_name}؟",
        f"أقول إيه في {cat_name} للطمأنينة والحفظ؟",
        f"ما المصدر الصحيح لذكر {snippet_plain}؟",
        f"كيف أستشعر معنى {snippet_plain} وأنا بقرأه؟",
        f"اشرحلي ببساطة ذكر {snippet_plain}",
    ] + profile["emotion_queries"]

    # Deduplicate preserving order, keep strictly 16..18 questions
    unique_questions: list[str] = []
    seen: set[str] = set()
    for q in candidates:
        q_clean = re.sub(r"\s+", " ", q).strip()
        if q_clean and q_clean not in seen:
            seen.add(q_clean)
            unique_questions.append(q_clean)
        if len(unique_questions) == 18:
            break

    bot_answer = (
        f"هذا الذكر من {cat_name} ووقته: {profile['timing']}. "
        f"يُقال ({repeat_str})، وفضله: {short_virtue.rstrip('.')}. "
        f"ومعنى «{first_word}»: {vocab[0]['meaning']}. "
        f"المصدر: {source_ref}."
    )

    return [
        {
            "intent": f"شرح وفضل وتوقيت ذكر «{snippet}» من {cat_name}",
            "user_questions": unique_questions,
            "bot_answer": bot_answer,
        }
    ]


def build_suggested_followups(cat_id: str, vocab: list[dict[str, str]]) -> list[str]:
    profile_followups = list(CATEGORY_PROFILES[cat_id]["followups"])
    word_clean = vocab[0]["word"].split()[0]
    custom_first = f"ما معنى {word_clean}؟"
    result = [custom_first, profile_followups[0], profile_followups[1]]
    # Strictly guarantee every chip is < 6 words
    safe_result: list[str] = []
    for item in result:
        words = item.split()
        if len(words) >= 6:
            item = " ".join(words[:5]).rstrip("؟") + "؟"
        safe_result.append(item)
    return safe_result


def run_audit_and_generate() -> None:
    azkar_path = APP_ASSETS_DIR / "azkar.json"
    raw_categories: list[dict[str, Any]] = json.loads(azkar_path.read_text(encoding="utf-8"))

    ai_dataset_ar: list[dict[str, Any]] = []
    upgraded_azkar_categories: list[dict[str, Any]] = []
    compact_metadata_map: dict[str, dict[str, Any]] = {}

    global_seq = 0
    stats = {"valid": 0, "corrected": 0, "weak_replaced": 0, "merged": len(MERGED_DUPLICATE_IDS)}

    for cat in raw_categories:
        cat_id = cat["id"]
        cat_name_ar = cat["nameAr"]
        cat_name_en = cat["nameEn"]

        processed_items: list[dict[str, Any]] = []
        for raw_item in cat["azkarList"]:
            orig_id = int(raw_item["id"])
            if orig_id in MERGED_DUPLICATE_IDS or orig_id in SPLIT_CHILD_IDS:
                continue

            if orig_id in SPLIT_ENTRIES:
                for split_item in SPLIT_ENTRIES[orig_id]:
                    processed_items.append(dict(split_item))
                continue

            item = dict(raw_item)
            override = ITEM_OVERRIDES.get(orig_id)
            if override:
                item.update(override)
            else:
                item["audit_status"] = "valid"
                item["audit_notes"] = "نص صحيح محقق ومطابق لمصدره في حصن المسلم أو الصحيحين."
            processed_items.append(item)

        # Apply traditional prophetic ordering when defined
        if cat_id in PROPHETIC_CATEGORY_ORDER:
            order_rank = {iid: idx for idx, iid in enumerate(PROPHETIC_CATEGORY_ORDER[cat_id])}
            processed_items.sort(key=lambda x: order_rank.get(int(x["id"]), 9999))

        upgraded_list: list[dict[str, Any]] = []
        for order_idx, item in enumerate(processed_items, start=1):
            global_seq += 1
            item_id = int(item["id"])
            dhikr_text = re.sub(r"[ \t]+", " ", item["text"]).strip()
            if "سورة " in item.get("source", "") or "آية الكرسي" in extract_dhikr_snippet(dhikr_text):
                dhikr_text = dhikr_text.rstrip(".")
            repeat_num = int(item.get("repetition", 1))
            if repeat_num < 1:
                repeat_num = 1
            source = item.get("source", "").strip()
            hadith_no = item.get("hadithNumber", "").strip()
            source_ref = f"{source} — رقم {hadith_no}" if hadith_no else source

            raw_virtue = item.get("short_virtue") or item.get("virtue") or ""
            short_virtue = shorten_virtue_under_15_words(raw_virtue, cat_name_ar)
            vocab = extract_vocabulary(dhikr_text)
            explanation = build_detailed_explanation(
                cat_id=cat_id,
                cat_name=cat_name_ar,
                dhikr_text=dhikr_text,
                virtue=item.get("virtue") or short_virtue,
                source_ref=source_ref,
                repeat_num=repeat_num,
                orig_id=item_id,
            )
            qa_pairs = build_qa_pairs(
                cat_id=cat_id,
                cat_name=cat_name_ar,
                dhikr_text=dhikr_text,
                short_virtue=short_virtue,
                source_ref=source_ref,
                repeat_num=repeat_num,
                vocab=vocab,
            )
            followups = build_suggested_followups(cat_id, vocab)
            audit_status = item.get("audit_status", "valid")
            audit_notes = item.get("audit_notes", "نص صحيح محقق ومطابق لمصدره.")
            stats[audit_status] = stats.get(audit_status, 0) + 1

            seq_id = f"ar_{cat_id}_{order_idx:02d}"
            ai_entry = {
                "id": seq_id,
                "order_index": order_idx,
                "language": "ar",
                "category": cat_name_ar,
                "audit_status": audit_status,
                "audit_notes": audit_notes,
                "dhikr_text": dhikr_text,
                "transliteration": "",
                "repeat_count_number": repeat_num,
                "repeat_count_label": format_repeat_label_ar(repeat_num),
                "source_reference": source_ref,
                "short_virtue_for_card": short_virtue,
                "detailed_explanation": explanation,
                "vocabulary_explanation": vocab,
                "qa_pairs": qa_pairs,
                "suggested_followups": followups,
            }
            ai_dataset_ar.append(ai_entry)

            # Backward-compatible upgraded azkar.json entry
            upgraded_list.append({
                "id": item_id,
                "text": dhikr_text,
                "translation": item.get("translation", ""),
                "source": source,
                "sourceEn": item.get("sourceEn", ""),
                "hadithNumber": hadith_no,
                "virtue": short_virtue,
                "virtueEn": item.get("virtueEn", ""),
                "repetition": repeat_num,
            })

            # Compact offline metadata keyed by "{categoryId}_{dhikrId}"
            compact_metadata_map[f"{cat_id}_{item_id}"] = {
                "aiId": seq_id,
                "categoryId": cat_id,
                "categoryName": cat_name_ar,
                "dhikrId": item_id,
                "orderIndex": order_idx,
                "auditStatus": audit_status,
                "shortVirtue": short_virtue,
                "detailedExplanation": explanation,
                "vocabulary": vocab,
                "suggestedFollowups": followups,
                "botAnswer": qa_pairs[0]["bot_answer"],
                "keywords": list(dict.fromkeys(
                    [cat_name_ar]
                    + [v["word"] for v in vocab[:3]]
                    + qa_pairs[0]["user_questions"][:6]
                )),
            }

        upgraded_azkar_categories.append({
            "id": cat_id,
            "nameAr": cat_name_ar,
            "nameEn": cat_name_en,
            "azkarList": upgraded_list,
        })

    OUTPUT_DATA_DIR.mkdir(parents=True, exist_ok=True)
    db_ar_path = OUTPUT_DATA_DIR / "db_ar.json"
    db_ar_path.write_text(
        json.dumps(ai_dataset_ar, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    # Upgrade app's primary azkar.json with all audited corrections
    azkar_path.write_text(
        json.dumps(upgraded_azkar_categories, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    # Compact minified offline metadata for instant ✨ AI BottomSheet without APK bloat
    metadata_path = APP_ASSETS_DIR / "ai_metadata_ar.json"
    metadata_path.write_text(
        json.dumps(compact_metadata_map, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )

    print(f"Generated {db_ar_path} ({len(ai_dataset_ar)} audited entries, {db_ar_path.stat().st_size / 1024:.1f} KB)")
    print(f"Upgraded  {azkar_path} ({len(upgraded_azkar_categories)} categories, {azkar_path.stat().st_size / 1024:.1f} KB)")
    print(f"Generated {metadata_path} ({metadata_path.stat().st_size / 1024:.1f} KB compact)")
    print(f"Audit summary: {stats}")


if __name__ == "__main__":
    run_audit_and_generate()
