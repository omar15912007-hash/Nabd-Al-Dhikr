def shorten_virtue_under_15_words(virtue: str, category_name: str) -> str:
    v = re.sub(r"\s+", " ", virtue).strip()
    if not v:
        v = f"ذكر نبوي صحيح من {category_name} يبعث الطمأنينة والبركة."
    words = v.split()
    if len(words) < 15:
        return v
    # Trim cleanly at punctuation or max 13 words
    for sep in ("،", ".", "؛"):
        parts = v.split(sep)
        if parts and 4 <= len(parts[0].split()) <= 14:
            return parts[0].strip() + "."
    return " ".join(words[:13]).rstrip("،؛:") + "."


